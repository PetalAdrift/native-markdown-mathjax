/* =========================================
   Markdown Sticky Notes Theme
   ========================================= */

(() => {
  "use strict";

  let isProcessing = false;
  let observer = null;
  let updateTimer = null;

  function findMarkdownRoot() {
    /*
     * Try some common Markdown-preview containers first.
     *
     * You can add your editor's container class here if needed.
     */
    const selectors = [
      ".markdown-body",
      ".markdown-preview-view",
      ".markdown-preview",
      ".markdown-content",
      ".preview",
      "article",
      "main"
    ];

    for (const selector of selectors) {
      const element = document.querySelector(selector);

      if (element && element.querySelector("h2")) {
        return element;
      }
    }

    /*
     * Fallback:
     * Find the first H2 and use its parent.
     */
    const firstH2 = document.querySelector("h2");

    if (firstH2 && firstH2.parentElement) {
      return firstH2.parentElement;
    }

    /*
     * Last resort.
     */
    return document.body;
  }


  function slugify(text) {
    return text
      .toLowerCase()
      .trim()
      .replace(/[^\p{L}\p{N}\s_-]/gu, "")
      .replace(/\s+/g, "-")
      .replace(/-+/g, "-")
      .replace(/^-|-$/g, "");
  }


  function ensureUniqueHeadingIds(root) {
    const headings = root.querySelectorAll(
      ".markdown-section > h2, .markdown-section h3"
    );

    const usedIds = new Set();

    /*
     * Preserve IDs that already exist elsewhere in the document.
     */
    document.querySelectorAll("[id]").forEach((element) => {
      if (!headings.length || !Array.from(headings).includes(element)) {
        usedIds.add(element.id);
      }
    });

    headings.forEach((heading) => {
      /*
       * Keep an existing heading ID if it is usable.
       */
      if (heading.id && !usedIds.has(heading.id)) {
        usedIds.add(heading.id);
        return;
      }

      const base = slugify(heading.textContent) || "section";

      let id = base;
      let counter = 2;

      while (usedIds.has(id)) {
        id = `${base}-${counter}`;
        counter++;
      }

      heading.id = id;
      usedIds.add(id);
    });
  }


  function unwrapExistingSections(root) {
    const sections = Array.from(
      root.querySelectorAll(":scope > .markdown-section")
    );

    sections.forEach((section) => {
      while (section.firstChild) {
        root.insertBefore(section.firstChild, section);
      }

      section.remove();
    });
  }


  function removeExistingTOC(root) {
    const toc = root.querySelector(":scope > #table-of-contents");

    if (toc) {
      toc.remove();
    }
  }


  /* ============================================================
     Wrap each ## section in a sticky-note container
     ============================================================ */

  function wrapMarkdownSections(root) {
    /*
     * Remove wrappers generated by an earlier run first.
     */
    unwrapExistingSections(root);

    const children = Array.from(root.children);

    let currentSection = null;

    children.forEach((element) => {
      /*
       * Ignore our generated TOC.
       */
      if (element.id === "table-of-contents") {
        return;
      }

      /*
       * Every H2 begins a new note.
       */
      if (element.tagName === "H2") {
        currentSection = document.createElement("section");

        currentSection.className = "markdown-section";

        /*
         * Mark it as generated by this script.
         */
        currentSection.dataset.markdownStickySection = "true";

        root.insertBefore(currentSection, element);

        currentSection.appendChild(element);

        return;
      }

      /*
       * Everything following the H2 belongs to the same note
       * until another H2 is encountered.
       */
      if (currentSection) {
        currentSection.appendChild(element);
      }
    });
  }


  /* ============================================================
     Generate automatic table of contents
     ============================================================ */

  function generateTableOfContents(root) {
    removeExistingTOC(root);

    const sections = Array.from(
      root.querySelectorAll(":scope > .markdown-section")
    );

    if (sections.length === 0) {
      return;
    }

    ensureUniqueHeadingIds(root);

    const toc = document.createElement("nav");

    toc.id = "table-of-contents";
    toc.setAttribute("aria-label", "Table of contents");

    /*
     * TOC title
     */
    const tocTitle = document.createElement("h2");

    tocTitle.textContent = "Contents";

    /*
     * Do NOT let the TOC heading itself become part of
     * our section hierarchy.
     */
    tocTitle.className = "toc-title";

    toc.appendChild(tocTitle);


    /*
     * Main TOC list
     */
    const mainList = document.createElement("ul");

    mainList.className = "toc-list";

    toc.appendChild(mainList);


    sections.forEach((section) => {
      const h2 = section.querySelector(":scope > h2");

      if (!h2) {
        return;
      }


      /* --------------------------------------------------------
         Main section entry
         -------------------------------------------------------- */

      const sectionItem = document.createElement("li");

      sectionItem.className = "toc-section";

      const sectionLink = document.createElement("a");

      sectionLink.href = `#${h2.id}`;
      sectionLink.textContent = h2.textContent.trim();

      sectionItem.appendChild(sectionLink);

      mainList.appendChild(sectionItem);


      /* --------------------------------------------------------
         ### subsection entries
         -------------------------------------------------------- */

      const h3Headings = Array.from(
        section.querySelectorAll("h3")
      );

      if (h3Headings.length > 0) {
        const subsectionList = document.createElement("ul");

        subsectionList.className = "toc-subsections";

        h3Headings.forEach((h3) => {
          const subsectionItem = document.createElement("li");

          const subsectionLink = document.createElement("a");

          subsectionLink.href = `#${h3.id}`;
          subsectionLink.textContent = h3.textContent.trim();

          subsectionItem.appendChild(subsectionLink);

          subsectionList.appendChild(subsectionItem);
        });

        sectionItem.appendChild(subsectionList);
      }
    });


    /*
     * Put the TOC immediately before the first sticky note.
     *
     * Anything before the first ## section — such as the H1 and
     * introductory paragraph — stays above the TOC.
     */
    const firstSection = root.querySelector(
      ":scope > .markdown-section"
    );

    if (firstSection) {
      root.insertBefore(toc, firstSection);
    }
  }


  function enableTOCNavigation(root) {
    const toc = root.querySelector("#table-of-contents");

    if (!toc) {
      return;
    }

    toc.querySelectorAll("a[href^='#']").forEach((link) => {
      link.addEventListener("click", (event) => {
        const id = decodeURIComponent(
          link.getAttribute("href").substring(1)
        );

        const target = document.getElementById(id);

        if (!target) {
          return;
        }

        event.preventDefault();

        target.scrollIntoView({
          behavior: "smooth",
          block: "start"
        });

        /*
         * Update the URL without forcing another jump.
         */
        if (history.replaceState) {
          history.replaceState(null, "", `#${id}`);
        }
      });
    });
  }


  /* ============================================================
     Main initialization function
     ============================================================ */

  function initializeNotes() {
    if (isProcessing) {
      return;
    }

    const root = findMarkdownRoot();

    if (!root) {
      return;
    }

    /*
     * We need at least one ## heading.
     */
    if (!root.querySelector("h2")) {
      return;
    }

    isProcessing = true;

    /*
     * Temporarily stop observing while we modify the DOM.
     * Otherwise our own changes would trigger another update.
     */
    if (observer) {
      observer.disconnect();
    }

    try {
      removeExistingTOC(root);
      wrapMarkdownSections(root);
      generateTableOfContents(root);
      enableTOCNavigation(root);
    } catch (error) {
      console.error(
        "Markdown sticky-note initialization failed:",
        error
      );
    } finally {
      isProcessing = false;

      startObserver();
    }
  }


  function scheduleRefresh() {
    clearTimeout(updateTimer);

    updateTimer = setTimeout(() => {
      initializeNotes();
    }, 150);
  }


  function startObserver() {
    const root = findMarkdownRoot();

    if (!root) {
      return;
    }

    if (observer) {
      observer.disconnect();
    }

    observer = new MutationObserver((mutations) => {
      /*
       * Ignore mutations caused solely by our generated elements.
       */
      const meaningfulChange = mutations.some((mutation) => {
        return Array.from(mutation.addedNodes).some((node) => {
          if (!(node instanceof Element)) {
            return false;
          }

          if (
            node.id === "table-of-contents" ||
            node.classList?.contains("markdown-section")
          ) {
            return false;
          }

          return true;
        });
      });

      if (meaningfulChange) {
        scheduleRefresh();
      }
    });

    observer.observe(root, {
      childList: true,
      subtree: true
    });
  }


  /* ============================================================
     Start

     Handles both cases:

     1. Script executes while the document is still loading.
     2. Markdown renderer injects the script after DOMContentLoaded.
     ============================================================ */

  function start() {
    /*
     * A very short delay helps Markdown previewers finish inserting
     * their rendered HTML before we inspect it.
     */
    setTimeout(() => {
      initializeNotes();
    }, 50);
  }


  if (document.readyState === "loading") {
    document.addEventListener(
      "DOMContentLoaded",
      start,
      { once: true }
    );
  } else {
    start();
  }

})();